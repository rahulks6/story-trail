#!/usr/bin/env node
// Builds mobile/src/components/iconPaths.ts from Lucide's SVGs (lucide-static, ISC licence): one
// list of SVG path strings per Katkee icon name, every shape (circle, rect, line, polyline...)
// turned into a path so Icon.tsx draws them all the same way.
//
//   npm pack lucide-static@0.460.0 && tar -xzf lucide-static-0.460.0.tgz
//   node scripts/icon-paths.cjs package/icons
//
// To change an icon, change its Lucide name below and run it again.
const fs = require("node:fs");
const path = require("node:path");

const LUCIDE_VERSION = "0.460.0";

/** Katkee icon name -> Lucide icon. */
const MAP = {
  home: "house", search: "search", create: "plus", add: "plus", activity: "heart", like: "heart",
  comment: "message-circle", share: "send", dm: "message-square", profile: "user", more: "ellipsis",
  close: "x", flash: "zap", timer: "timer", gallery: "image", flip: "switch-camera", text: "type",
  sticker: "sticker", emoji: "smile", draw: "brush", audioOn: "volume-2", audioMuted: "volume-x",
  crop: "crop", trim: "scissors", appearance: "sun-moon", language: "languages", viewers: "eye",
  insights: "chart-no-axes-column", newChat: "square-pen", attach: "paperclip", notifications: "bell",
  trash: "trash-2", check: "check", edit: "pencil", undo: "undo-2", redo: "redo-2", reply: "reply",
  copy: "copy", report: "flag", logout: "log-out", star: "star", settings: "settings", archive: "history",
  save: "download", privacy: "lock", data: "database", help: "circle-help", about: "info",
  following: "user-check", mention: "at-sign", filter: "sliders-horizontal", alignLeft: "align-left",
  alignCenter: "align-center", alignRight: "align-right", textBackground: "baseline", music: "music",
  play: "play", pause: "pause", camera: "camera", mic: "mic", forward: "forward", pin: "pin",
  call: "phone", video: "video", endCall: "phone-off", micOff: "mic-off", videoOff: "video-off",
  chevron: "chevron-right", expand: "chevron-down", minus: "minus", up: "arrow-up", down: "arrow-down",
  left: "arrow-left", right: "arrow-right", backAndroid: "arrow-left", backIos: "chevron-left",
};

const num = (v) => Number.parseFloat(v);
const fmt = (n) => String(Math.round(n * 1000) / 1000);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-z0-9-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

function shapeToPath(name, a) {
  switch (name) {
    case "path": return a.d;
    case "circle": case "ellipse": {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx ?? a.r), ry = num(a.ry ?? a.r);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(rx * 2)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-rx * 2)} 0Z`;
    }
    case "rect": {
      const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height);
      const r = Math.min(num(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + r)} ${fmt(y)}h${fmt(w - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(r)}v${fmt(h - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(r)}h${fmt(-(w - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(-r)}v${fmt(-(h - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(-r)}Z`;
    }
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(num);
      let d = `M${fmt(pts[0])} ${fmt(pts[1])}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${fmt(pts[i])} ${fmt(pts[i + 1])}`;
      return name === "polygon" ? d + "Z" : d;
    }
    default: throw new Error(`unsupported <${name}>`);
  }
}

function iconPaths(file) {
  const svg = fs.readFileSync(file, "utf8");
  return [...svg.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)\/?>/g)].map((m) => shapeToPath(m[1], attrs(m[2])));
}

const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/icon-paths.cjs <lucide-static>/icons"); process.exit(1); }
const licence = fs.readFileSync(path.join(dir, "../LICENSE"), "utf8").trim().split("\n").map((l) => ` * ${l}`.trimEnd()).join("\n");
const lines = Object.entries(MAP).map(([k, v]) => `  ${k}: [${iconPaths(path.join(dir, `${v}.svg`)).map((d) => `'${d}'`).join(", ")}],`);
const out = `// Generated by scripts/icon-paths.cjs from Lucide ${LUCIDE_VERSION} (lucide-static). Don't edit by hand.
/**
 * Katkee's icons are drawn from Lucide (https://lucide.dev), one consistent family: a 24-point
 * grid, 2-point round strokes. Its licence:
 *
${licence}
 */
export const ICON_PATHS: Record<string, readonly string[]> = {
${lines.join("\n")}
};
`;
const target = path.join(__dirname, "../mobile/src/components/iconPaths.ts");
fs.writeFileSync(target, out);
console.log(`${Object.keys(MAP).length} icons -> ${path.relative(process.cwd(), target)}`);
