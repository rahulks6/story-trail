import React from 'react';
import {I18nManager, Platform, StyleSheet, View, type StyleProp, type TextStyle} from 'react-native';
import Svg, {Path, Circle, Rect, G} from 'react-native-svg';
import {colors} from '../theme/colors';
import type {IconName} from '../theme/icons';
import {ICON_PATHS} from './iconPaths';

/** Names drawn as another icon: the filled heart is the heart drawn solid, and so on. */
const ALIAS:Partial<Record<IconName,string>>={liked:'like',clear:'close',changeCover:'gallery',starFilled:'star',
 // Each platform's own back: an arrow on Android (as its headers draw it), a chevron on iPhone.
 back:Platform.OS==='android'?'backAndroid':'backIos',
 // Share is each platform's own share symbol; Send (a message, a reply) is the paper plane.
 share:Platform.OS==='android'?'shareAndroid':'shareIos'};

/** The verified badge: a rosette (eight scallops) with the tick cut out of it in the background's contrast colour. */
/** Icons that point along the reading direction: mirrored in a right-to-left language (Arabic). */
const DIRECTIONAL=new Set<string>(['back','chevron','forward']);

const MIRRORED={transform:[{scaleX:-1}]};
const ROSETTE='M12 1.8L15.2 4.2L19.2 4.8L19.8 8.8L22.2 12L19.8 15.2L19.2 19.2L15.2 19.8L12 22.2L8.8 19.8L4.8 19.2L4.2 15.2L1.8 12L4.2 8.8L4.8 4.8L8.8 4.2Z';

/**
 * Katkee's icons: Lucide's family (iconPaths.ts, generated by scripts/icon-paths.cjs) on a 24-point
 * grid with round 2-point strokes, so every icon in the app shares one weight and one style.
 * Liked hearts, filled stars and the current tab are drawn solid. Decorative by default: the
 * owning control supplies its accessible label/state.
 */
export function Icon({name,size,color,selected=false,framed=false,style}: {name:IconName;size?:number;color?:string;selected?:boolean;
 /** Draw it inside a rounded square: the tab bar's Create, as Instagram draws its +. */
 framed?:boolean;style?:StyleProp<TextStyle>}): React.JSX.Element {
 const flat=StyleSheet.flatten(style)||{};
 const length=size??flat.fontSize??24;
 const ink=color??flat.color??(selected?colors.accentText:colors.textPrimary);
 // The current tab's icon is drawn solid (home, messages, profile) or heavier (search, create).
 const solidWhenSelected=name==='home'||name==='dm'||name==='profile';
 const filled=name==='liked'||name==='starFilled'||name==='verified'||(selected&&solidWhenSelected);
 const weight=selected&&!solidWhenSelected?2.5:2;
 const key=ALIAS[name]??name;
 const margins={margin:flat.margin,marginTop:flat.marginTop,marginBottom:flat.marginBottom,marginLeft:flat.marginLeft,marginRight:flat.marginRight};
 return <View pointerEvents="none" accessible={false} style={margins}>
  <Svg width={length} height={length} viewBox="0 0 24 24" accessible={false} style={I18nManager.isRTL&&DIRECTIONAL.has(name)?MIRRORED:undefined}>
   <G stroke={ink} strokeWidth={weight} strokeLinecap="round" strokeLinejoin="round" fill={filled?ink:'none'}>
    {framed?<><Rect x={3} y={3} width={18} height={18} rx={5}/><Path d="M12 8v8M8 12h8"/></>
     :key==='capture'?<><Circle cx={12} cy={12} r={11}/><Circle cx={12} cy={12} r={8.5} fill={ink}/></>
     :key==='verified'?<><Path d={ROSETTE}/><Path d="M8 12.2l2.8 2.8L16.2 9.4" stroke={colors.onAccentText} strokeWidth={2.2} fill="none"/></>
     // A solid home keeps its door, as a hole in the house (on any background).
     :filled&&key==='home'?<Path d={`${ICON_PATHS.home![1]}M9.5 21v-5a1.5 1.5 0 0 1 1.5-1.5h2a1.5 1.5 0 0 1 1.5 1.5v5Z`} fillRule="evenodd" stroke="none"/>
     :(ICON_PATHS[key]??[]).map((d,i)=><Path key={i} d={d}/>)}
   </G>
  </Svg>
 </View>;
}
